-- ZTBD – schemat relacyjny (PostgreSQL 18)
-- Wykonuje się automatycznie przy PIERWSZYM starcie pustej bazy
-- (docker-entrypoint-initdb.d). Po zmianie: ./scripts/db.sh reset postgres
--
-- Zgodny z ERD z planu projektu i z nagłówkami CSV generatora
-- (Record_generation/generate.py, katalog sql/).
--
-- Celowo BEZ indeksów pomocniczych: są tylko PK, UNIQUE i FK.
-- Indeksy do drugiej serii pomiarów: infra/postgres/indexes/create.sql
-- (./scripts/db.sh indexes postgres on|off).
--
-- Kolejność tabel = kolejność importu (najpierw tabele nadrzędne).

-- ---------------------------------------------------------------------
-- Słowniki (stały rozmiar: 24 kategorie, 12 dostawców, 5 magazynów)
-- ---------------------------------------------------------------------

CREATE TABLE categories (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   integer      REFERENCES categories (id),
    name        varchar(100) NOT NULL
);

CREATE TABLE suppliers (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL,
    country     char(2)      NOT NULL,
    email       varchar(255) NOT NULL
);

CREATE TABLE warehouses (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    city        varchar(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- Klienci
-- ---------------------------------------------------------------------

CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       varchar(255) NOT NULL UNIQUE,
    first_name  varchar(100) NOT NULL,
    last_name   varchar(100) NOT NULL,
    created_at  timestamp    NOT NULL
);

CREATE TABLE addresses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    street      varchar(255) NOT NULL,
    city        varchar(100) NOT NULL,
    postal_code varchar(10)  NOT NULL,
    country     char(2)      NOT NULL,
    is_default  boolean      NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------------
-- Katalog i magazyn
-- ---------------------------------------------------------------------

CREATE TABLE products (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id integer       NOT NULL REFERENCES suppliers (id),
    name        varchar(255)  NOT NULL,
    sku         varchar(32)   NOT NULL UNIQUE,
    price       numeric(10,2) NOT NULL CHECK (price >= 0),
    attributes  jsonb         NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE product_categories (
    product_id  bigint  NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    category_id integer NOT NULL REFERENCES categories (id),
    PRIMARY KEY (product_id, category_id)
);

CREATE TABLE inventory (
    product_id   bigint    NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    warehouse_id integer   NOT NULL REFERENCES warehouses (id),
    quantity     integer   NOT NULL CHECK (quantity >= 0),
    updated_at   timestamp NOT NULL,
    PRIMARY KEY (product_id, warehouse_id)
);

-- ---------------------------------------------------------------------
-- Zamówienia i logistyka
-- ---------------------------------------------------------------------

CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint        NOT NULL REFERENCES users (id),
    address_id  bigint        NOT NULL REFERENCES addresses (id),
    status      varchar(20)   NOT NULL
                CHECK (status IN ('PENDING', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    total       numeric(12,2) NOT NULL CHECK (total >= 0),
    created_at  timestamp     NOT NULL
);

-- Główna tabela skalowana (100k → 10M wierszy).
CREATE TABLE order_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  bigint        NOT NULL REFERENCES products (id),
    order_id    bigint        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    quantity    integer       NOT NULL CHECK (quantity > 0),
    unit_price  numeric(10,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE payments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method      varchar(20)   NOT NULL,
    amount      numeric(12,2) NOT NULL CHECK (amount >= 0),
    status      varchar(20)   NOT NULL,
    paid_at     timestamp
);

CREATE TABLE shipments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    warehouse_id integer     NOT NULL REFERENCES warehouses (id),
    carrier      varchar(50) NOT NULL,
    status       varchar(20) NOT NULL,
    shipped_at   timestamp
);

CREATE TABLE reviews (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id  bigint    NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    rating      smallint  NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment     text,
    created_at  timestamp NOT NULL
);
